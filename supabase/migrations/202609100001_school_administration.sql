create policy "admins view school admins" on public.school_admins for select using (user_id = auth.uid() or public.is_school_admin(school_id));
create policy "admins view teachers" on public.teachers for select using (user_id = auth.uid() or public.is_school_admin(school_id));
create policy "admins manage teachers" on public.teachers for all using (public.is_school_admin(school_id)) with check (public.is_school_admin(school_id));
create policy "school members view classes" on public.classes for select using (public.is_school_admin(school_id) or exists (select 1 from public.teachers where user_id = auth.uid() and school_id = classes.school_id) or exists (select 1 from public.students where user_id = auth.uid() and school_id = classes.school_id));
create policy "admins manage classes" on public.classes for all using (public.is_school_admin(school_id)) with check (public.is_school_admin(school_id));
create policy "staff view teacher classes" on public.teacher_classes for select using (public.is_assigned_teacher(class_id) or exists (select 1 from public.classes where id = class_id and public.is_school_admin(school_id)));
create policy "admins manage teacher classes" on public.teacher_classes for all using (exists (select 1 from public.classes where id = class_id and public.is_school_admin(school_id))) with check (exists (select 1 from public.classes where id = teacher_classes.class_id and public.is_school_admin(school_id)));
create policy "members view student classes" on public.student_classes for select using (exists (select 1 from public.students where id = student_id and user_id = auth.uid()) or public.is_assigned_teacher(class_id) or exists (select 1 from public.classes where id = class_id and public.is_school_admin(school_id)));
create policy "admins manage student classes" on public.student_classes for all using (exists (select 1 from public.classes where id = class_id and public.is_school_admin(school_id))) with check (exists (select 1 from public.classes where id = student_classes.class_id and public.is_school_admin(school_id)));
create policy "admins manage invites" on public.invite_codes for all using (public.is_school_admin(school_id)) with check (public.is_school_admin(school_id));
create policy "staff view marks" on public.marks for select using (exists (select 1 from public.student_classes sc where sc.student_id = marks.student_id and (public.is_assigned_teacher(sc.class_id) or exists (select 1 from public.classes c where c.id = sc.class_id and public.is_school_admin(c.school_id)))));
create policy "teachers create marks" on public.marks for insert with check (teacher_id in (select id from public.teachers where user_id = auth.uid()) and exists (select 1 from public.student_classes sc where sc.student_id = marks.student_id and public.is_assigned_teacher(sc.class_id)));
create policy "students manage own completions" on public.study_session_completions for all using (exists (select 1 from public.students where id = student_id and user_id = auth.uid())) with check (exists (select 1 from public.students where id = study_session_completions.student_id and user_id = auth.uid()));
create policy "staff view completions" on public.study_session_completions for select using (exists (select 1 from public.student_classes sc where sc.student_id = study_session_completions.student_id and public.is_assigned_teacher(sc.class_id)) or exists (select 1 from public.students s where s.id = study_session_completions.student_id and public.is_school_admin(s.school_id)));
